const attrNames = ["title", "placeholder", "aria-label", "alt"];
const textOriginals = new WeakMap<Text, string>();
const attrOriginals = new WeakMap<Element, Record<string, string>>();

export function isEnglishLanguage(language?: string | null): boolean {
  return language === "en-US" || language === "en";
}

function translateCore(text: string): string {
  if (textMap[text]) return textMap[text];

  let next = text;
  const keys = Object.keys(phraseMap).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    next = next.replaceAll(key, phraseMap[key]);
  }

  if (next !== text) return next;
  return text;
}

export function translateUiText(value: string, language?: string | null): string {
  if (!isEnglishLanguage(language)) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  if (!core) return value;
  const translated = translateCore(core);
  return `${leading}${translated}${trailing}`;
}

function translateTextNode(node: Text, language: Lang) {
  const current = node.nodeValue ?? "";
  const previousOriginal = textOriginals.get(node);
  const previousTranslated = previousOriginal ? translateUiText(previousOriginal, "en-US") : null;
  const original =
    !previousOriginal || (current !== previousOriginal && current !== previousTranslated)
      ? current
      : previousOriginal;

  textOriginals.set(node, original);
  const next = language === "en-US" ? translateUiText(original, language) : original;
  if (current !== next) node.nodeValue = next;
}

function translateElementAttributes(element: Element, language: Lang) {
  const record = attrOriginals.get(element) ?? {};
  let changed = false;

  for (const attr of attrNames) {
    const current = element.getAttribute(attr);
    if (current == null) continue;

    const previousOriginal = record[attr];
    const previousTranslated = previousOriginal ? translateUiText(previousOriginal, "en-US") : null;
    const original =
      !previousOriginal || (current !== previousOriginal && current !== previousTranslated)
        ? current
        : previousOriginal;

    record[attr] = original;
    changed = true;
    const next = language === "en-US" ? translateUiText(original, language) : original;
    if (current !== next) element.setAttribute(attr, next);
  }

  if (changed) attrOriginals.set(element, record);
}

function shouldSkipElement(element: Element): boolean {
  return element.closest("[data-i18n-skip]") != null || ["SCRIPT", "STYLE"].includes(element.tagName);
}

function translateTree(root: Node, language: Lang) {
  if (root.nodeType === Node.TEXT_NODE) {
    const parent = root.parentElement;
    if (!parent || shouldSkipElement(parent)) return;
    translateTextNode(root as Text, language);
    return;
  }

  if (root.nodeType !== Node.ELEMENT_NODE) return;
  const element = root as Element;
  if (shouldSkipElement(element)) return;

  translateElementAttributes(element, language);
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.ELEMENT_NODE) {
      const el = node as Element;
      if (shouldSkipElement(el)) {
        node = walker.nextSibling();
        continue;
      }
      translateElementAttributes(el, language);
    } else if (node.nodeType === Node.TEXT_NODE) {
      const parent = node.parentElement;
      if (parent && !shouldSkipElement(parent)) translateTextNode(node as Text, language);
    }
    node = walker.nextNode();
  }
}

export function I18nRuntime() {
  const language = (useGlobalConfig(s => s.config?.app_language) || "zh-CN") as Lang;

  useEffect(() => {
    document.documentElement.lang = language === "en-US" ? "en" : "zh-CN";
    translateTree(document.body, language);

    const observer = new MutationObserver(mutations => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") {
          const parent = mutation.target.parentElement;
          if (parent && !shouldSkipElement(parent)) {
            translateTextNode(mutation.target as Text, language);
          }
        } else if (mutation.type === "attributes") {
          const element = mutation.target as Element;
          if (!shouldSkipElement(element)) translateElementAttributes(element, language);
        } else {
          mutation.addedNodes.forEach(node => translateTree(node, language));
        }
      }
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: attrNames,
    });

    return () => observer.disconnect();
  }, [language]);

  return null;
}
